import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal','--enable-webgl','--ignore-gpu-blocklist','--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport:{width:1440,height:900} });
const errs=[]; page.on('pageerror',e=>{errs.push(e.message);console.error(e.message)}); page.on('console',m=>{if(m.type()==='error'){errs.push(m.text());console.error(m.text())}});
await page.goto('http://127.0.0.1:5198/', { waitUntil:'networkidle' });
await page.waitForFunction(()=>window.__SCALEBOUND__?.ready,{timeout:45000});
await page.mouse.click(700,500);
await page.waitForTimeout(500);
console.log('audio1', await page.evaluate(async()=>{const a=window.__SCALEBOUND__.audio; return {started:a.started,state:a.ctx?.state,pad:a.padOscillators?.length,wind:a.windGain?.gain.value,enabled:a.enabled};}));
await page.click('#audioBtn');
await page.waitForTimeout(200);
console.log('audio2', await page.evaluate(()=>{const a=window.__SCALEBOUND__.audio; return {enabled:a.enabled, master:a.master?.gain.value, soundOn:window.__SCALEBOUND__.game.soundEnabled};}));
await page.click('#audioBtn');
await page.waitForTimeout(200);
console.log('audio3', await page.evaluate(()=>{const a=window.__SCALEBOUND__.audio; return {enabled:a.enabled, master:a.master?.gain.value, soundOn:window.__SCALEBOUND__.game.soundEnabled};}));
console.log('errs',errs);
await browser.close();
