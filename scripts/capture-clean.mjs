import { chromium } from 'playwright-core';
const [query='', prefix='clean'] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal','--enable-webgl','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs=[];
page.on('pageerror', e=>{errs.push(e.message);console.error('PAGEERROR',e.message);});
page.on('console', m=>{if(m.type()==='error'){errs.push(m.text());console.error('CONSOLE',m.text());}});
await page.goto('http://127.0.0.1:5198/'+query, { waitUntil:'networkidle' });
await page.waitForFunction(()=>window.__SCALEBOUND__?.ready,{timeout:45000});
await page.waitForTimeout(1200);
await page.screenshot({path:`screenshots/${prefix}-menu.png`});
await page.click('#startBtn');
await page.waitForFunction(()=>window.__SCALEBOUND__.game.mode==='flight',{timeout:10000});
await page.waitForTimeout(1000);
await page.evaluate(()=>window.__SCALEBOUND__.finishIntro());
await page.waitForTimeout(3800);
await page.screenshot({path:`screenshots/${prefix}-flight.png`});
console.log('state', await page.evaluate(()=>window.__SCALEBOUND__.state()));
console.log('errors', errs);
await browser.close();
