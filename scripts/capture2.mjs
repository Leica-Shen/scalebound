import { chromium } from 'playwright-core';
const args = process.argv.slice(2);
const query = args[0] || '';
const prefix = args[1] || 'v2';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal','--enable-webgl','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors=[];
page.on('console', m=>{ if(m.type()==='error') errors.push(m.text()); });
page.on('pageerror', e=>{ errors.push(e.message); console.error('PAGEERROR',e.message); });
await page.goto('http://127.0.0.1:5198/'+query, { waitUntil:'networkidle' });
const t0=Date.now();
await page.waitForFunction(()=>window.__SCALEBOUND__?.ready,{timeout:40000});
console.log('boot ms',Date.now()-t0);
await page.waitForTimeout(1400);
await page.screenshot({path:`screenshots/${prefix}-menu.png`});
console.log('menu state',await page.evaluate(()=>({...window.__SCALEBOUND__.state(), spawn:window.__SCALEBOUND__.world.spawn, props:{trees:window.__SCALEBOUND__.world.trunkMesh.count,rocks:window.__SCALEBOUND__.world.rockMesh.count}})));
await page.click('#startBtn');
await page.waitForFunction(()=>window.__SCALEBOUND__.game.mode==='flight',{timeout:10000});
await page.waitForTimeout(1300);
await page.evaluate(()=>window.__SCALEBOUND__.finishIntro());
await page.waitForTimeout(800);
await page.screenshot({path:`screenshots/${prefix}-flight.png`});
const fps = await page.evaluate(async()=>{
 let frames=0; const start=performance.now();
 await new Promise(res=>{const f=()=>{frames++; if(performance.now()-start<2000) requestAnimationFrame(f); else res();}; requestAnimationFrame(f);});
 return frames/2;
});
console.log('fps',fps,'flight state',await page.evaluate(()=>window.__SCALEBOUND__.state()));
// look down a bit / turn
await page.keyboard.down('KeyD');
await page.waitForTimeout(900);
await page.keyboard.up('KeyD');
await page.waitForTimeout(300);
await page.screenshot({path:`screenshots/${prefix}-flight2.png`});
console.log('errors',errors.slice(0,10));
await browser.close();
