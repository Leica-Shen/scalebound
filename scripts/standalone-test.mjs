import { chromium } from 'playwright-core';
import path from 'node:path';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal','--enable-webgl','--ignore-gpu-blocklist','--allow-file-access-from-files'] });
const page = await browser.newPage({ viewport:{width:1440,height:900} });
const errs=[]; const requests=[];
page.on('pageerror',e=>{errs.push(e.message);console.error('PAGEERROR',e.message)});
page.on('console',m=>{if(m.type()==='error'){errs.push(m.text());console.error(m.text())}});
page.on('request', r=>{ if(!r.url().startsWith('file:')&&!r.url().startsWith('data:')) requests.push(r.url()); });
const url='file://'+path.resolve('scalebound.html');
await page.goto(url,{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__SCALEBOUND__?.ready,{timeout:45000});
await page.waitForTimeout(1000);
console.log('ready state', await page.evaluate(()=>window.__SCALEBOUND__.state()));
console.log('font loaded', await page.evaluate(()=>document.fonts.check('12px Zpix')));
await page.screenshot({path:'screenshots/standalone-menu.png'});
await page.click('#startBtn');
await page.waitForFunction(()=>window.__SCALEBOUND__.game.mode==='flight',{timeout:10000});
await page.waitForTimeout(1200);
await page.evaluate(()=>window.__SCALEBOUND__.finishIntro());
await page.waitForTimeout(1200);
await page.screenshot({path:'screenshots/standalone-flight.png'});
console.log('flight state', await page.evaluate(()=>window.__SCALEBOUND__.state()));
console.log('external requests',requests);
console.log('errs',errs);
await browser.close();
